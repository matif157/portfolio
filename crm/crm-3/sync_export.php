/* ============================================================
   SPS CRM - MASTER SYNC EXPORT ENDPOINT
   Generated by SPS CRM Desktop settings (Deploy tab).
   ------------------------------------------------------------
     ?token=...&type=ping   -> "ok"
     ?token=...&type=db     -> complete syedpro_app dump (.sql)
