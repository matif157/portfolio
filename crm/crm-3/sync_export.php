define('SYNC_TOKEN', 'sps-sync-2026');
set_time_limit(0);
ini_set('memory_limit', '1024M');

/* DB used by the dump (edit here if this server differs).    */
define('MASTER_DB', 'syedpro_app');
define('MASTER_MYSQLDUMP', 'C:\\xampp\\mysql\\bin\\mysqldump.exe');
$MASTER_DB_USER = 'root';
$MASTER_DB_PASS = '';
$MASTER_DB_HOST = 'localhost';
$MASTER_DB_PORT = '3306';
putenv('MYSQL_PWD=' . $MASTER_DB_PASS);

function sync_fail($code, $msg) {
    http_response_code($code);
    header('Content-Type: text/plain; charset=utf-8');
    echo $msg;
    exit;
}

if (!isset($_GET['token']) || $_GET['token'] !== SYNC_TOKEN) {
    sync_fail(403, 'forbidden');
}

$type = isset($_GET['type']) ? $_GET['type'] : 'db';

if ($type === 'ping') {
    echo 'ok';
    exit;
}

if ($type === 'db') {
    $dump = MASTER_MYSQLDUMP;
    if (!is_file($dump)) {
        sync_fail(500, 'mysqldump not found at ' . $dump);
    }
    $args = '-u ' . $MASTER_DB_USER . ' --host=' . $MASTER_DB_HOST . ' --port=' . $MASTER_DB_PORT
          . ' --single-transaction --routines --triggers --databases ' . MASTER_DB;
    header('Content-Type: application/sql; charset=utf-8');
    header('Content-Disposition: attachment; filename=' . MASTER_DB . '_dump.sql');
    header('X-Content-Type-Options: nosniff');
    $cmd = escapeshellarg($dump) . ' ' . $args;
    passthru($cmd);
    exit;
}

